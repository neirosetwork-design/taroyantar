// День передаётся снаружи: при гидратации клиент берёт серверное значение,
// после монтирования пересчитывает — без рассинхрона рендеров.
export function pickCard(cards: TarotCard[], dayIndex: number): TarotCard {
  return cards[dayIndex % cards.length];
}

export function dayIndex(): number {
  return Math.floor(Date.now() / 86_400_000);
}
